"""Structured events intended for CLI and future dashboard consumers."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Mapping

from token_kv_agent_system.models import CommunicationMode


class EventType(str, Enum):
    DISCUSSION_NETWORK_UPDATED = "DISCUSSION_NETWORK_UPDATED"
    DISCUSSION_WORKER_READY = "DISCUSSION_WORKER_READY"
    DISCUSSION_STARTED = "DISCUSSION_STARTED"
    AGENT_TURN_STARTED = "AGENT_TURN_STARTED"
    AGENT_TURN_COMPLETED = "AGENT_TURN_COMPLETED"
    AUTO_DECISION = 'AUTO_DECISION'
    AUTO_DECISION_FAILED = 'AUTO_DECISION_FAILED'
    HANDOFF_STARTED = "HANDOFF_STARTED"
    HANDOFF_COMPLETED = "HANDOFF_COMPLETED"
    HANDOFF_UNCONFIRMED = "HANDOFF_UNCONFIRMED"
    HANDOFF_FAILED = "HANDOFF_FAILED"
    DISCUSSION_FINALIZING = "DISCUSSION_FINALIZING"
    DISCUSSION_COMPLETED = "DISCUSSION_COMPLETED"
    DISCUSSION_FAILED = "DISCUSSION_FAILED"
    AGENT_GENERATION_STARTED = "AGENT_GENERATION_STARTED"
    AGENT_GENERATION_FINISHED = "AGENT_GENERATION_FINISHED"
    MODE_SELECTED = "MODE_SELECTED"
    TRANSMISSION_STARTED = "TRANSMISSION_STARTED"
    TRANSMISSION_FINISHED = "TRANSMISSION_FINISHED"
    NETWORK_STATE_CHANGED = "NETWORK_STATE_CHANGED"
    REAL_TOKEN_HANDOFF_STARTED = "REAL_TOKEN_HANDOFF_STARTED"
    TOKEN_SERIALIZED = "TOKEN_SERIALIZED"
    TOKEN_TRANSFERRED = "TOKEN_TRANSFERRED"
    TOKEN_DESERIALIZED = "TOKEN_DESERIALIZED"
    RECEIVER_PREFILL_FINISHED = "RECEIVER_PREFILL_FINISHED"
    REAL_TOKEN_HANDOFF_FINISHED = "REAL_TOKEN_HANDOFF_FINISHED"
    REAL_TOKEN_HANDOFF_FAILED = "REAL_TOKEN_HANDOFF_FAILED"
    REAL_KV_HANDOFF_STARTED = "REAL_KV_HANDOFF_STARTED"
    KV_PREPARED = "KV_PREPARED"
    KV_SERIALIZED = "KV_SERIALIZED"
    KV_TRANSFERRED = "KV_TRANSFERRED"
    KV_DESERIALIZED = "KV_DESERIALIZED"
    KV_RESTORED = "KV_RESTORED"
    REAL_KV_HANDOFF_FINISHED = "REAL_KV_HANDOFF_FINISHED"
    REAL_KV_HANDOFF_FAILED = "REAL_KV_HANDOFF_FAILED"
    REAL_ADAPTIVE_HANDOFF_STARTED = "REAL_ADAPTIVE_HANDOFF_STARTED"
    REAL_SELECTION_MADE = "REAL_SELECTION_MADE"
    SELECTED_PATH_STARTED = "SELECTED_PATH_STARTED"
    REAL_ADAPTIVE_HANDOFF_FINISHED = "REAL_ADAPTIVE_HANDOFF_FINISHED"
    REAL_ADAPTIVE_HANDOFF_FAILED = "REAL_ADAPTIVE_HANDOFF_FAILED"


@dataclass(frozen=True)
class CommunicationEvent:
    event_type: EventType
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    source_agent_id: str | None = None
    target_agent_id: str | None = None
    mode: CommunicationMode | None = None
    payload_bytes: int | None = None
    transmission_latency_ms: float | None = None
    estimated_e2e_latency_ms: float | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)
